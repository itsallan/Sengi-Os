#!/bin/sh
# Turns the Phosphor Bold icons in ui/icons/phosphor/bold into ui/icon-paths.slint,
# so the interface can draw them as Slint paths in token colours.
#
#   render-icons.sh            regenerate ui/icon-paths.slint
#   render-icons.sh --check    fail if it is stale
#
# Each file is one filled path on a 256 unit grid, which is all this reads.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
dir=$root/ui/icons/phosphor/bold
out=$root/ui/icon-paths.slint

generate() {
	echo "// Generated by scripts/render-icons.sh from ui/icons/phosphor/bold. Do not edit."
	echo "// Phosphor Icons, MIT licence, see THIRD-PARTY-NOTICES.md."
	echo
	echo "export global IconPaths {"
	echo "    // The outline of an icon on a 256 unit grid, or nothing for a name"
	echo "    // that has no file."
	echo "    public pure function path(name: string) -> string {"
	for file in "$dir"/*-bold.svg; do
		name=$(basename "$file" -bold.svg)
		if [ "$(grep -o '<path' "$file" | wc -l)" -ne 1 ]; then
			echo "$file: expected exactly one path" >&2
			exit 1
		fi
		d=$(sed -n 's/.*<path d="\([^"]*\)".*/\1/p' "$file")
		[ -n "$d" ] || { echo "$file: no path data" >&2; exit 1; }
		printf '        name == "%s" ? "%s" :\n' "$name" "$d"
	done
	echo '        ""'
	echo "    }"
	echo "}"
}

case "${1:-}" in
--check)
	generate | cmp -s - "$out" || { echo "stale: ui/icon-paths.slint (run scripts/render-icons.sh)" >&2; exit 1; }
	;;
"")
	generate >"$out.tmp"
	mv "$out.tmp" "$out"
	echo "rendered ui/icon-paths.slint"
	;;
*)
	echo "usage: render-icons.sh [--check]" >&2
	exit 2
	;;
esac
