    #[test]
    fn applying_writes_then_settles_then_removes() {
        let tmp = TempDir::new();
        tmp.write("etc/labwc/rc.xml", SYSTEM_RC);
        tmp.write("etc/labwc/environment", "XCURSOR_SIZE=24\n");
        let dirs = dirs(&tmp);
        let rc = tmp.path().join("home/labwc/rc.xml");
        let environment = tmp.path().join("home/labwc/environment");

        let plain = settings("");
        let applied = apply(&dirs, &plain);
        assert_eq!(
            (applied.rc.clone(), applied.environment.clone()),
            (Ok(Wrote::Unchanged), Ok(Wrote::Unchanged))
        );
        assert!(!applied.changed());
        assert!(!rc.exists() && !environment.exists());

        let changed =
            settings("[mouse]\nleft-handed = true\n[clock]\ntime-zone = \"Europe/Paris\"\n");
        let applied = apply(&dirs, &changed);
        assert_eq!(
            (applied.rc.clone(), applied.environment.clone()),
            (Ok(Wrote::Written), Ok(Wrote::Written))
        );
        assert!(applied.changed() && applied.problems().is_empty());
        assert!(fs::read_to_string(&rc)
            .unwrap()
            .contains("<name>Sengi</name>"));
        assert!(fs::read_to_string(&environment)
            .unwrap()
            .contains("XCURSOR_SIZE=24\nTZ=Europe/Paris"));

        assert!(!apply(&dirs, &changed).changed());

        // The system file changed in an update: the copy follows.
        tmp.write("etc/labwc/rc.xml", &SYSTEM_RC.replace("Sengi", "Sengi2"));
        assert_eq!(apply(&dirs, &changed).rc, Ok(Wrote::Written));
        assert!(fs::read_to_string(&rc).unwrap().contains("Sengi2"));

        let applied = apply(&dirs, &plain);
        assert_eq!(
            (applied.rc, applied.environment),
            (Ok(Wrote::Removed), Ok(Wrote::Removed))
        );
        assert!(!rc.exists() && !environment.exists());
    }

