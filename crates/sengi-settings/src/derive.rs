//! The files other programs read, written from the settings.
//!
//! labwc takes the keyboard layout and the time zone from its
//! `environment` file and the key repeat and pointer settings from
//! `rc.xml`. It reads the user's copy of each *instead of* the system's,
//! not on top of it, and the system's `rc.xml` is where the Sengi OS theme
//! and key bindings are. So the user's copy cannot hold our few settings
//! alone: it is written as the system file with our part added.
//!
//! * `~/.config/labwc/rc.xml` is generated whole. Its first comment says
//!   so. It is only written when a setting differs from labwc's default,
//!   and removed again when none does, so most machines never have one.
//!   A `rc.xml` without that comment is somebody's own and is left alone.
//! * `~/.config/labwc/environment` keeps whatever the user wrote in it.
//!   What we add lives between marker comments: the system file's lines
//!   above the user's, which therefore win over them, and the settings
//!   below.
//!
//! The copy goes stale when an update changes the system file. Running
//! `sengi-settings --apply` at the start of the session, before labwc,
//! writes it afresh; that is what the option is for.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use crate::settings::{Settings, KEYS};
use crate::store::{self, Dirs};

const RC: &str = "labwc/rc.xml";
const ENVIRONMENT: &str = "labwc/environment";

const RC_MARK: &str = "<!-- Generated by sengi-settings";
const BEGIN: &str = "# >>> sengi-settings: written from sengi-os/settings.toml, do not edit";
const END: &str = "# <<< sengi-settings";

/// A config file larger than this is not read.
const MAX_BYTES: u64 = 1024 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Wrote {
    /// The file already said the right thing, or was rightly absent.
    Unchanged,
    Written,
    /// Nothing of ours is needed any more.
    Removed,
    /// The user has a file of their own there. It was not touched.
    Foreign,
}

fn yes_no(flag: bool) -> &'static str {
    if flag {
        "yes"
    } else {
        "no"
    }
}

/// Whether any of the settings that live in `rc.xml` differ from the
/// defaults, which are labwc's own.
fn rc_needed(settings: &Settings) -> bool {
    KEYS.iter()
        .filter(|(section, key, _)| {
            matches!(*section, "mouse" | "touchpad")
                || (*section == "keyboard" && key.starts_with("repeat-"))
        })
        .any(|(section, key, _)| {
            let plain = Settings::default();
            settings.get(section, key) != plain.get(section, key)
        })
}

fn rc_block(settings: &Settings) -> String {
    let speed = |section: &str| format!("{:.2}", settings.number(section, "speed") as f64 / 100.0);
    format!(
        "  <keyboard>\n    <repeatRate>{}</repeatRate>\n    <repeatDelay>{}</repeatDelay>\n  </keyboard>\n\
         \x20 <libinput>\n    <device category=\"non-touch\">\n      <naturalScroll>{}</naturalScroll>\n\
         \x20     <leftHanded>{}</leftHanded>\n      <pointerSpeed>{}</pointerSpeed>\n    </device>\n\
         \x20   <device category=\"touchpad\">\n      <naturalScroll>{}</naturalScroll>\n\
         \x20     <pointerSpeed>{}</pointerSpeed>\n      <tap>{}</tap>\n\
         \x20     <disableWhileTyping>{}</disableWhileTyping>\n    </device>\n  </libinput>\n",
        settings.number("keyboard", "repeat-rate"),
        settings.number("keyboard", "repeat-delay"),
        yes_no(settings.flag("mouse", "natural-scroll")),
        yes_no(settings.flag("mouse", "left-handed")),
        speed("mouse"),
        yes_no(settings.flag("touchpad", "natural-scroll")),
        speed("touchpad"),
        yes_no(settings.flag("touchpad", "tap-to-click")),
        yes_no(settings.flag("touchpad", "disable-while-typing")),
    )
}

/// The user's `rc.xml`: the system's with our settings added at the end,
/// where they override anything said earlier. `None` when no file is
/// needed.
pub fn rc_text(system: Option<(&Path, &str)>, settings: &Settings) -> Option<String> {
    if !rc_needed(settings) {
        return None;
    }
    let block = rc_block(settings);
    let (source, body) = match system {
        Some((path, text)) => (path.display().to_string(), text),
        None => (
            "nothing: there was no system rc.xml".to_string(),
            "<?xml version=\"1.0\"?>\n<labwc_config>\n</labwc_config>\n",
        ),
    };
    let mark = format!(
        "{RC_MARK} from {source}.\n     Change sengi-os/settings.toml or use Settings; this file is rewritten. -->\n"
    );
    // The mark goes after the XML declaration, which must stay first.
    let (declaration, rest) = match body.find("?>") {
        Some(end) if body.trim_start().starts_with("<?xml") => {
            let end = end + 2;
            (&body[..end], body[end..].trim_start_matches('\n'))
        }
        _ => ("", body),
    };
    let close = rest.rfind("</labwc_config>")?;
    let mut out = String::with_capacity(body.len() + mark.len() + block.len() + 2);
    if !declaration.is_empty() {
        out.push_str(declaration);
        out.push('\n');
    }
    out.push_str(&mark);
    out.push_str(&rest[..close]);
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out.push_str(&block);
    out.push_str(&rest[close..]);
    if !out.ends_with('\n') {
        out.push('\n');
    }
    Some(out)
}

/// The lines of ours that go into labwc's environment.
fn environment_lines(settings: &Settings) -> Vec<String> {
    let mut lines = Vec::new();
    let zone = settings.text("clock", "time-zone");
    if !zone.is_empty() {
        lines.push(format!("TZ={zone}"));
    }
    let layouts = settings.layouts();
    let switch = settings.text("keyboard", "switch");
    let plain = layouts.len() == 1 && layouts[0].layout == "us" && layouts[0].variant.is_empty();
    if !layouts.is_empty() && !(plain && switch.is_empty()) {
        let join = |pick: fn(&crate::settings::Layout) -> &str| {
            layouts.iter().map(pick).collect::<Vec<_>>().join(",")
        };
        lines.push(format!("XKB_DEFAULT_LAYOUT={}", join(|l| &l.layout)));
        lines.push(format!("XKB_DEFAULT_VARIANT={}", join(|l| &l.variant)));
        lines.push(format!("XKB_DEFAULT_OPTIONS={switch}"));
    }
    lines
}

/// The user's `environment`: the system file's lines between markers,
/// then the user's own lines as they were, then between markers again
/// what Settings adds. `None` when the file would hold nothing.
pub fn environment_text(
    system: Option<&str>,
    existing: Option<&str>,
    settings: &Settings,
) -> Option<String> {
    let ours = environment_lines(settings);
    // The user's lines: everything outside the markers.
    let mut theirs: Vec<&str> = Vec::new();
    let mut inside = false;
    for line in existing.unwrap_or_default().lines() {
        if line.trim() == BEGIN {
            inside = true;
        } else if line.trim() == END {
            inside = false;
        } else if !inside {
            theirs.push(line);
        }
    }
    // The blank lines that set their lines apart from ours are ours too.
    let blank = |line: &&str| line.trim().is_empty();
    let first = theirs.iter().position(|line| !blank(line));
    let last = theirs.iter().rposition(|line| !blank(line));
    let theirs = match (first, last) {
        (Some(first), Some(last)) => &theirs[first..=last],
        _ => &[],
    };
    if ours.is_empty() && theirs.is_empty() {
        return None;
    }
    // labwc stops at the user's file, so what the system's says has to be
    // said again here.
    let inherited: Vec<&str> = system
        .unwrap_or_default()
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .collect();
    let block = |out: &mut String, lines: &mut dyn Iterator<Item = &str>| {
        out.push_str(BEGIN);
        out.push('\n');
        for line in lines {
            out.push_str(line);
            out.push('\n');
        }
        out.push_str(END);
        out.push('\n');
    };
    let ours = || ours.iter().map(String::as_str);
    let mut out = String::new();
    if theirs.is_empty() {
        block(&mut out, &mut inherited.iter().copied().chain(ours()));
        return Some(out);
    }
    // labwc sets each variable as it comes to its line, so of two lines
    // for one variable the later wins. The system's lines go first, where
    // the user's own can override them as they did when their file was the
    // only one read. What was chosen in Settings goes last: it is there
    // only when it is not the default, and then it was chosen after
    // whatever the file says.
    if !inherited.is_empty() {
        block(&mut out, &mut inherited.iter().copied());
        out.push('\n');
    }
    for line in theirs {
        out.push_str(line);
        out.push('\n');
    }
    if ours().next().is_some() {
        out.push('\n');
        block(&mut out, &mut ours());
    }
    Some(out)
}

fn read(path: &Path) -> Option<String> {
    let meta = fs::metadata(path).ok()?;
    if !meta.is_file() || meta.len() > MAX_BYTES {
        return None;
    }
    fs::read_to_string(path).ok()
}

fn settle(path: &Path, existing: Option<&str>, wanted: Option<String>) -> Result<Wrote, String> {
    match (existing, wanted) {
        (None, None) => Ok(Wrote::Unchanged),
        (Some(old), Some(new)) if old == new => Ok(Wrote::Unchanged),
        (_, Some(new)) => store::write_atomic(path, &new)
            .map(|()| Wrote::Written)
            .map_err(|error| format!("could not write {}: {error}", path.display())),
        (Some(_), None) => fs::remove_file(path)
            .map(|()| Wrote::Removed)
            .map_err(|error| format!("could not remove {}: {error}", path.display())),
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Applied {
    pub rc: Result<Wrote, String>,
    pub environment: Result<Wrote, String>,
}

impl Applied {
    /// Whether labwc has anything new to read.
    pub fn changed(&self) -> bool {
        let changed =
            |result: &Result<Wrote, String>| matches!(result, Ok(Wrote::Written | Wrote::Removed));
        changed(&self.rc) || changed(&self.environment)
    }

    pub fn problems(&self) -> Vec<String> {
        let mut found = Vec::new();
        for result in [&self.rc, &self.environment] {
            if let Err(problem) = result {
                found.push(problem.clone());
            }
        }
        if self.rc == Ok(Wrote::Foreign) {
            found.push(
                "~/.config/labwc/rc.xml is your own file, so keyboard repeat and pointer \
                 settings were not written to it"
                    .to_string(),
            );
        }
        found
    }
}

/// Bring both files in line with `settings`.
pub fn apply(dirs: &Dirs, settings: &Settings) -> Applied {
    let Some(user_rc) = dirs.user(RC) else {
        let nowhere = Err("there is no home directory to write labwc's files in".to_string());
        return Applied {
            rc: nowhere.clone(),
            environment: nowhere,
        };
    };
    let user_environment: PathBuf = dirs.user(ENVIRONMENT).unwrap_or_default();

    let existing = read(&user_rc);
    let rc = if user_rc.exists()
        && !existing
            .as_deref()
            .is_some_and(|text| text.contains(RC_MARK))
    {
        Ok(Wrote::Foreign)
    } else {
        let system_path = dirs.system(RC);
        let system_text = system_path.as_deref().and_then(read);
        let system = system_path.as_deref().zip(system_text.as_deref());
        match rc_text(system, settings) {
            None if rc_needed(settings) => {
                Err("the system rc.xml has no </labwc_config> to add settings before".to_string())
            }
            wanted => settle(&user_rc, existing.as_deref(), wanted),
        }
    };

    let existing = read(&user_environment);
    let environment = if user_environment.exists() && existing.is_none() {
        Err(format!("cannot read {}", user_environment.display()))
    } else {
        let system = dirs.system(ENVIRONMENT).as_deref().and_then(read);
        let wanted = environment_text(system.as_deref(), existing.as_deref(), settings);
        settle(&user_environment, existing.as_deref(), wanted)
    };
    Applied { rc, environment }
}

/// Have the running labwc read its files again. Blocks until the command
/// has run; call it off the UI thread. Without a labwc to tell (no
/// `LABWC_PID`) there is nothing to do.
pub fn reconfigure() -> bool {
    if std::env::var_os("LABWC_PID").is_none() {
        return false;
    }
    Command::new("labwc")
        .arg("--reconfigure")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .is_ok_and(|status| status.success())
}

