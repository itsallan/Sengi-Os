    const SYSTEM_RC: &str = "<?xml version=\"1.0\"?>\n<labwc_config>\n  <theme>\n    <name>Sengi</name>\n  </theme>\n  <keyboard>\n    <default />\n  </keyboard>\n</labwc_config>\n";

    fn settings(user: &str) -> Settings {
        Settings::from_documents(Document::default(), Document::parse(user).0, None)
    }

    #[test]
    fn default_settings_need_no_files() {
        let plain = settings("");
        assert_eq!(
            rc_text(Some((Path::new("/etc/rc.xml"), SYSTEM_RC)), &plain),
            None
        );
        assert_eq!(
            environment_text(Some("XCURSOR_SIZE=24\n"), None, &plain),
            None
        );
        // Settings that live elsewhere do not count.
        let other = settings("[power]\nlock-after = 60\n[clock]\nformat = \"12h\"\n");
        assert_eq!(rc_text(None, &other), None);
        assert_eq!(environment_text(None, None, &other), None);
    }

    #[test]
    fn the_generated_rc_is_the_system_file_plus_our_settings() {
        let s = settings(
            "[keyboard]\nrepeat-rate = 40\n[mouse]\nspeed = -50\nleft-handed = true\n[touchpad]\nnatural-scroll = true\ntap-to-click = false\n",
        );
        let text = rc_text(Some((Path::new("/etc/xdg/labwc/rc.xml"), SYSTEM_RC)), &s).unwrap();
        assert!(text.starts_with(
            "<?xml version=\"1.0\"?>\n<!-- Generated by sengi-settings from /etc/xdg/labwc/rc.xml."
        ));
        // Everything the system file said is still there, in order.
        let mut at = 0;
        for line in SYSTEM_RC.lines() {
            at += text[at..]
                .find(line)
                .unwrap_or_else(|| panic!("lost {line}"));
        }
        assert!(text.ends_with("  </libinput>\n</labwc_config>\n"));
        assert_eq!(text.matches("</labwc_config>").count(), 1);
        for wanted in [
            "<repeatRate>40</repeatRate>",
            "<repeatDelay>600</repeatDelay>",
            "<pointerSpeed>-0.50</pointerSpeed>",
            "<leftHanded>yes</leftHanded>",
            "<tap>no</tap>",
            "<disableWhileTyping>yes</disableWhileTyping>",
        ] {
            assert!(text.contains(wanted), "{wanted} in {text}");
        }
        let touchpad = text.split("category=\"touchpad\"").nth(1).unwrap();
        assert!(touchpad.contains("<naturalScroll>yes</naturalScroll>"));
    }

    #[test]
    fn an_rc_without_a_system_file_still_stands_alone() {
        let s = settings("[mouse]\nnatural-scroll = true\n");
        let text = rc_text(None, &s).unwrap();
        assert!(text.contains("<labwc_config>"));
        assert!(text.contains(RC_MARK));
        // A system file that is not labwc's cannot be added to.
        assert_eq!(rc_text(Some((Path::new("/x"), "<nonsense/>")), &s), None);
    }

    #[test]
    fn the_environment_carries_zone_and_layouts() {
        let s = settings(
            "[clock]\ntime-zone = \"Europe/Paris\"\n[keyboard]\nlayouts = [\"us\", \"fr(azerty)\"]\nswitch = \"grp:alt_shift_toggle\"\n",
        );
        let text = environment_text(Some("# cursor\nXCURSOR_SIZE=24\n"), None, &s).unwrap();
        assert_eq!(
            text,
            format!(
                "{BEGIN}\nXCURSOR_SIZE=24\nTZ=Europe/Paris\nXKB_DEFAULT_LAYOUT=us,fr\n\
                 XKB_DEFAULT_VARIANT=,azerty\nXKB_DEFAULT_OPTIONS=grp:alt_shift_toggle\n{END}\n"
            )
        );
        // One layout that is not the default is still written.
        let de = settings("[keyboard]\nlayouts = [\"de\"]\n");
        let text = environment_text(None, None, &de).unwrap();
        assert!(
            text.contains("XKB_DEFAULT_LAYOUT=de\nXKB_DEFAULT_VARIANT=\nXKB_DEFAULT_OPTIONS=\n")
        );
        assert!(!text.contains("TZ="));
    }

    #[test]
    fn the_users_own_environment_lines_are_kept() {
        let s = settings("[clock]\ntime-zone = \"Asia/Tokyo\"\n");
        let first = environment_text(None, Some("MOZ_USE_XINPUT2=1\n# mine\n"), &s).unwrap();
        assert_eq!(
            first,
            format!("MOZ_USE_XINPUT2=1\n# mine\n\n{BEGIN}\nTZ=Asia/Tokyo\n{END}\n")
        );
        // Writing again changes nothing, however often.
        assert_eq!(environment_text(None, Some(&first), &s).unwrap(), first);
        // Back to defaults: our block goes, their lines stay.
        let back = environment_text(None, Some(&first), &settings("")).unwrap();
        assert_eq!(back, "MOZ_USE_XINPUT2=1\n# mine\n");
        // A file that held only our block is not needed at all.
        let only = environment_text(None, None, &s).unwrap();
        assert_eq!(environment_text(None, Some(&only), &settings("")), None);
        // With their own lines and a system file, the system's lines must
        // be repeated even when we have none of our own.
        let kept =
            environment_text(Some("XCURSOR_SIZE=24\n"), Some("A=1\n"), &settings("")).unwrap();
        assert_eq!(kept, format!("{BEGIN}\nXCURSOR_SIZE=24\n{END}\n\nA=1\n"));
    }

    /// The environment labwc 0.8 ends up with after reading `text`: a
    /// line that starts with `#` is a comment, a line without `=` is
    /// skipped, name and value are trimmed, and each line is a `setenv`
    /// that replaces what an earlier one set (`process_line` in its
    /// `src/config/session.c`).
    fn as_labwc_reads(text: &str) -> std::collections::BTreeMap<&str, &str> {
        text.lines()
            .filter(|line| !line.starts_with('#'))
            .filter_map(|line| line.split_once('='))
            .map(|(name, value)| (name.trim(), value.trim()))
            .filter(|(name, _)| !name.is_empty())
            .collect()
    }

    #[test]
    fn the_users_lines_win_over_the_systems_and_settings_over_both() {
        let system = "XCURSOR_SIZE=24\nXCURSOR_THEME=Sengi\n";
        let theirs = "XCURSOR_SIZE=48\nTZ=Asia/Tokyo\n";
        // Nothing set in Settings: the file says what it would have said
        // had labwc read the system's file and then the user's.
        let plain = environment_text(Some(system), Some(theirs), &settings("")).unwrap();
        let read = as_labwc_reads(&plain);
        assert_eq!(read["XCURSOR_SIZE"], "48");
        assert_eq!(read["XCURSOR_THEME"], "Sengi");
        assert_eq!(read["TZ"], "Asia/Tokyo");
        // A zone chosen in Settings is the later word on the zone, and
        // changes nothing else.
        let paris = settings("[clock]\ntime-zone = \"Europe/Paris\"\n");
        let chosen = environment_text(Some(system), Some(&plain), &paris).unwrap();
        assert_eq!(
            chosen,
            format!(
                "{BEGIN}\nXCURSOR_SIZE=24\nXCURSOR_THEME=Sengi\n{END}\n\n\
                 XCURSOR_SIZE=48\nTZ=Asia/Tokyo\n\n{BEGIN}\nTZ=Europe/Paris\n{END}\n"
            )
        );
        let read = as_labwc_reads(&chosen);
        assert_eq!(read["XCURSOR_SIZE"], "48");
        assert_eq!(read["TZ"], "Europe/Paris");
        assert_eq!(
            environment_text(Some(system), Some(&chosen), &paris).unwrap(),
            chosen
        );
        // Back to the default: theirs counts again.
        let back = environment_text(Some(system), Some(&chosen), &settings("")).unwrap();
        assert_eq!(back, plain);
    }

    #[test]
    fn a_file_in_the_old_order_is_put_in_the_new_one() {
        // As written before: the user's lines, then one block holding the
        // system's lines and ours, where the system's 24 beat the user's 48.
        let old = format!("XCURSOR_SIZE=48\n\n{BEGIN}\nXCURSOR_SIZE=24\nTZ=Europe/Paris\n{END}\n");
        assert_eq!(as_labwc_reads(&old)["XCURSOR_SIZE"], "24");
        let paris = settings("[clock]\ntime-zone = \"Europe/Paris\"\n");
        let new = environment_text(Some("XCURSOR_SIZE=24\n"), Some(&old), &paris).unwrap();
        assert_eq!(
            new,
            format!(
                "{BEGIN}\nXCURSOR_SIZE=24\n{END}\n\nXCURSOR_SIZE=48\n\n{BEGIN}\nTZ=Europe/Paris\n{END}\n"
            )
        );
        assert_eq!(as_labwc_reads(&new)["XCURSOR_SIZE"], "48");
    }

    #[test]
    fn applying_keeps_the_mode_and_writes_through_a_link() {
        use std::os::unix::fs::PermissionsExt;
        let tmp = TempDir::new();
        tmp.write("etc/labwc/environment", "XCURSOR_SIZE=24\n");
        tmp.write("dotfiles/environment", "XCURSOR_SIZE=48\n");
        let target = tmp.path().join("dotfiles/environment");
        fs::set_permissions(&target, fs::Permissions::from_mode(0o600)).unwrap();
        fs::create_dir_all(tmp.path().join("home/labwc")).unwrap();
        let link = tmp.path().join("home/labwc/environment");
        std::os::unix::fs::symlink(&target, &link).unwrap();

        let paris = settings("[clock]\ntime-zone = \"Europe/Paris\"\n");
        assert_eq!(apply(&dirs(&tmp), &paris).environment, Ok(Wrote::Written));
        assert!(fs::symlink_metadata(&link).unwrap().is_symlink());
        let written = fs::read_to_string(&target).unwrap();
        assert_eq!(as_labwc_reads(&written)["XCURSOR_SIZE"], "48");
        assert_eq!(as_labwc_reads(&written)["TZ"], "Europe/Paris");
        assert_eq!(
            fs::metadata(&target).unwrap().permissions().mode() & 0o7777,
            0o600
        );
    }

