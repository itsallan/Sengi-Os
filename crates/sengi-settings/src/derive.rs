//! The files other programs read, written from the settings.
//!
//! labwc takes the keyboard layout and the time zone from its
//! `environment` file and the key repeat and pointer settings from
//! `rc.xml`. It reads the user's copy of each *instead of* the system's,
//! not on top of it, and the system's `rc.xml` is where the Sengi OS theme
//! and key bindings are. So the user's copy cannot hold our few settings
//! alone: it is written as the system file with our part added.
//!
//! * `~/.config/labwc/rc.xml` is generated whole. Its first comment says
//!   so. It is only written when a setting differs from labwc's default,
//!   and removed again when none does, so most machines never have one.
//!   A `rc.xml` without that comment is somebody's own and is left alone.
//! * `~/.config/labwc/environment` keeps whatever the user wrote in it.
//!   What we add lives between marker comments: the system file's lines
//!   above the user's, which therefore win over them, and the settings
//!   below.
//!
//! The copy goes stale when an update changes the system file. Running
//! `sengi-settings --apply` at the start of the session, before labwc,
//! writes it afresh; that is what the option is for.

